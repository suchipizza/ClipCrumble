"""todo.md — the human checklist, regenerated from brief.yaml + run.yaml + accounts.yaml + schedule.json at every stage.

Sections: pre-flight · per-slot actions (time-ordered) · post-posting actions · standing rules · kill conditions ·
Unknowns (every brief field that was defaulted).
"""
from __future__ import annotations

import datetime as dt

from .util import REPO, Campaign, load_json, load_yaml


def accounts_cfg() -> dict:
    return load_yaml(REPO / "accounts.yaml", {}) or {}


def account_fit(brief: dict, run: dict, accts: dict) -> list[str]:
    """Exclusivity conflicts refuse the account; low US % under a US rule warns; unverified CR -> pre-flight."""
    out = []
    geo = (brief.get("audience") or {}).get("geo_rule") or ""
    today = dt.date.today()
    for a in run.get("accounts", []):
        acc = accts.get(a)
        if not acc:
            out.append(f"REFUSE {a}: not in accounts.yaml"); continue
        ex = acc.get("exclusive_until")
        if ex and acc.get("exclusive_campaign") not in (None, run.get("slug")) and dt.date.fromisoformat(str(ex)) >= today:
            out.append(f"REFUSE {a}: exclusive to {acc['exclusive_campaign']} until {ex}")
        if "US" in geo and acc.get("us_pct") is not None and float(acc["us_pct"]) < 30:
            out.append(f"WARN {a}: measured US {acc['us_pct']}% under a '{geo}' rule — your decision before posting")
        if (brief.get("marketplace") or "").startswith("Content Rewards") and not acc.get("content_rewards_verified"):
            out.append(f"PREFLIGHT {a}: link and verify @{acc.get('handle', a)} in Content Rewards (bio code) before the first slot")
        if acc.get("platform") == "tiktok" and (acc.get("tiktok_account_type") or "").lower() == "business" \
                and acc.get("tiktok_branded_toggle", True):   # accounts.yaml: false = owner chose to post unbranded
            out.append(f"PREFLIGHT {a}: TikTok business account — Metricool cannot set the branded-content toggle; set it in-app per post")
    return out


def write(c: Campaign, notes: list[str] | None = None) -> str:
    brief = load_yaml(c.root / "brief.yaml", {}) or {}
    run = load_yaml(c.root / "run.yaml", {}) or {}
    sched = load_json(c.out / "schedule.json", None)
    accts = accounts_cfg()
    title = brief.get("title") or c.slug
    deadline = (brief.get("submission_chain") or [{}])[0].get("deadline_after_post_min")
    where = brief.get("marketplace", "?")
    L = [f"# To-do — {title}", "", f"_Generated {dt.datetime.now():%Y-%m-%d %H:%M}. Regenerated by every stage; edit tracker/tracker.csv, not this file._", ""]

    L += ["## 1. Pre-flight (before the first slot)", ""]
    inv = load_json(c.working / "inventory.json")
    if not inv:
        L.append(f"- [ ] Footage: download from {brief.get('approved_footage_source') or 'the brief'} and run `clipcrumble ingest {c.slug} --from <folder or zips>`")
    else:
        L.append(f"- [x] Footage in place: {inv['count']} files, {inv['total_minutes']} min ({', '.join(inv['types'])})")
    if brief.get("watermark"):
        L.append(f"- [ ] Watermark/asset: {brief['watermark']}")
    L.append(f"- [ ] Join the campaign on {where} with every posting account; check the live campaign page for rule changes "
             "(budget left, min payout, CPM) — the brief snapshot can be stale")
    for h in brief.get("official_handles") or []:
        L.append(f"- [ ] Verify {h} is the official account in TikTok and in Instagram (official handle listed in the brief; tagging is not required)")
    for line in account_fit(brief, run, accts):
        L.append(f"- [ ] {line}")
    if not run.get("accounts"):
        L.append("- [ ] Choose posting accounts in run.yaml (accounts.yaml lists them)")
    ok_rclone = load_json(c.out / "hosting_check.json", {}) or {}
    if not ok_rclone.get("ready"):
        L.append("- [ ] One-time: `! rclone config` → new remote `gdrive` (Google Drive, full scope) → browser login")
    if (run.get("scheduler_route") or "auto") in ("auto", "api"):
        L.append("- [ ] One-time: put METRICOOL_USER_TOKEN and METRICOOL_USER_ID in ClipCrumble/.env; add each account's "
                 "Metricool brand name + blogId to accounts.yaml")
    if brief.get("ai_tooling_risk") == "high":
        L.append("- [ ] AI-tooling risk HIGH: the brief restricts AI tools — decide whether to run this campaign at all")
    L.append("")

    L += ["## 2. At each slot (time-ordered)", ""]
    if sched:
        L += ["| local time | ET | account | post | do | submit by |", "|---|---|---|---|---|---|"]
        for p in sched["posts"]:
            moved = " (moved)" if p.get("flags") else ""
            L.append(f"| {p['slot_local'][5:16].replace('T', ' ')}{moved} | {p['slot_target_tz'][11:16]} | {p['account']} | "
                     f"`{p['post_id']}` | open the app → confirm it is live → copy URL → submit on {where} → log URL + submission id in tracker | "
                     f"{p['submit_deadline'][11:16] if p.get('submit_deadline') else '—'} |")
        if brief.get("pinned_comment"):
            L.append(f"\nPin the comment at every slot: {brief['pinned_comment']}")
        if sched.get("route") == "csv":
            L += ["", "**Import the CSV first:** Metricool → Planning → ⋯ → Import CSV → `out/metricool.csv` → date format "
                  "`YYYY-MM-DD`, time `HH:mm:ss` → check preview → Import. Then open one post per brand and confirm the video loaded."]
        for f in sched.get("failed", []):
            L.append(f"- [ ] API scheduling failed for {f} — it is in metricool.csv; import that row by hand")
    else:
        L.append("_Not scheduled yet._")
    L.append("")

    L += ["## 3. After posting", ""]
    sec = brief.get("second_step")
    if sec:
        L.append(f"- [ ] {sec.get('step')}: {sec.get('when')} — evidence: {sec.get('evidence')}")
    else:
        L.append("- No second step: the brief asks for no demographics, ticket or form, so no screen recording to make.")
    L.append("- [ ] Daily 10:00 (calendar): check every live post — views, engagement, comments; update tracker manual columns")
    L.append("")

    L += ["## 4. Standing rules", ""]
    L.append(f"- Keep every post live ≥ {brief.get('post_must_stay_live_days', 30)} days; likes visible; never edit a caption after submission")
    L.append(f"- Max {brief.get('daily_cap_per_platform', 5)} posts per platform per day; never the same file on two pages or platforms")
    L.append(f"- Engagement minimum {(brief.get('audience') or {}).get('engagement_min', '?')}")
    if brief.get("exclusivity_days"):
        L.append(f"- Page exclusivity: no other campaign on these accounts for {brief['exclusivity_days']} days")
    L.append("")

    L += ["## 5. Kill conditions", ""]
    geo = (brief.get("audience") or {}).get("geo_rule")
    if geo:
        L.append(f"- Stop scheduling on any account whose measured audience fails '{geo}'")
    L += ["- The campaign page shows budget exhausted or the campaign closed → cancel remaining Metricool posts",
          "- Any rejection citing caption/footage rules → pause and re-check the gates before the next slot", ""]

    L += ["## 6. Unknowns (brief fields that were defaulted — check them on the live campaign page)", ""]
    for k, v in (brief.get("_unknowns") or {}).items():
        L.append(f"- `{k}`: {v}")
    if notes:
        L += ["", "## Notes from the last run", ""] + [f"- {n}" for n in notes]
    text = "\n".join(L) + "\n"
    (c.out / "todo.md").write_text(text, encoding="utf-8")
    return text
